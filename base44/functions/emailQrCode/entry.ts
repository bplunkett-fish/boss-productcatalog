import { createClientFromRequest } from 'npm:@base44/sdk@0.8.49';

// Emails a generated QR code (PNG attached, SVG as a download link) to the
// calling admin's own address. SVG can't be an email attachment (unsupported
// extension), so the client uploads it to public storage and passes the URL.
export default async function(req) {
  try {
    const base44 = createClientFromRequest(req);
    const user = await base44.auth.me();
    if (!user) return Response.json({ error: 'Unauthorized' }, { status: 401 });
    if (user.role !== 'admin') return Response.json({ error: 'Forbidden' }, { status: 403 });

    const body = await req.json().catch(() => ({}));
    const serial = (body.serial_number || '').toString().trim();
    const pngBase64 = (body.png_base64 || '').toString().trim();
    const svgUrl = (body.svg_url || '').toString().trim();

    if (!serial) return Response.json({ error: 'Serial number is required' }, { status: 400 });
    if (!pngBase64) return Response.json({ error: 'PNG data is required' }, { status: 400 });

    // Strip control characters and cap length to prevent content injection.
    const cleanSerial = serial.replace(/[\x00-\x1F\x7F]/g, '').slice(0, 60);
    const fileSerial = cleanSerial.replace(/[^\w.-]/g, '_').slice(0, 40) || 'serial';
    const claimUrl = `https://hypersonic-sync-your-gear.base44.app/claim?serial=${encodeURIComponent(cleanSerial)}`;

    const html = `
      <div style="font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', sans-serif; max-width: 520px; margin: 0 auto; color: #1f2937;">
        <h2 style="margin: 0 0 8px;">QR code for serial ${cleanSerial}</h2>
        <p style="margin: 0 0 16px; color: #6b7280;">Scanning this code opens the app and adds the product to the user's catalog after confirmation.</p>
        <p style="margin: 0 0 8px;"><strong>Claim link:</strong><br><a href="${claimUrl}">${claimUrl}</a></p>
        <p style="margin: 16px 0 8px;"><strong>PNG (transparent):</strong> attached to this email.</p>
        ${svgUrl ? `<p style="margin: 0 0 8px;"><strong>SVG:</strong> <a href="${svgUrl}">Download SVG file</a></p>` : ''}
        <hr style="margin: 24px 0; border: none; border-top: 1px solid #e5e7eb;">
        <p style="margin: 0; font-size: 12px; color: #9ca3af;">Generated by ProductSync Pro · QR Code Generator</p>
      </div>`;

    await base44.asServiceRole.integrations.Core.SendEmail({
      to: user.email,
      subject: `QR code for serial ${cleanSerial}`,
      html,
      attachments: [{ filename: `qr-${fileSerial}.png`, content: pngBase64 }]
    });

    return Response.json({ status: 'sent', to: user.email });
  } catch (error) {
    return Response.json({ error: error.message }, { status: 500 });
  }
}