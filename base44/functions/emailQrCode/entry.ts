import { createClientFromRequest } from 'npm:@base44/sdk@0.8.49';
import JSZip from 'npm:jszip@3.10.1';

// Emails a generated QR code to the calling admin's own address. The PNG and
// SVG are bundled into a single zip (MyBOSS-QR-<serial>.zip), uploaded to
// public storage, and delivered as a download link — the email integration
// refuses archive attachments, so a link is the supported delivery method.
export default async function(req) {
  try {
    const base44 = createClientFromRequest(req);
    const user = await base44.auth.me();
    if (!user) return Response.json({ error: 'Unauthorized' }, { status: 401 });
    if (user.role !== 'admin') return Response.json({ error: 'Forbidden' }, { status: 403 });

    const body = await req.json().catch(() => ({}));
    const serial = (body.serial_number || '').toString().trim();
    const svgString = (body.svg_string || '').toString();
    const pngBase64 = (body.png_base64 || '').toString().trim().replace(/^data:image\/png;base64,/, '');

    if (!serial) return Response.json({ error: 'Serial number is required' }, { status: 400 });
    if (!/^[A-Za-z0-9]+$/.test(serial)) {
      return Response.json({ error: 'Serial number must be alphanumeric (letters and numbers only)' }, { status: 400 });
    }
    if (!svgString || !pngBase64) return Response.json({ error: 'QR code data is required' }, { status: 400 });

    const safeSerial = serial.replace(/[^A-Za-z0-9]/g, '');
    const base = `MyBOSS-QR-${safeSerial}`;

    const zip = new JSZip();
    zip.file(`${base}.png`, pngBase64, { base64: true });
    zip.file(`${base}.svg`, svgString);
    const zipBytes = await zip.generateAsync({ type: 'uint8array' });
    const file = new File([zipBytes], `${base}.zip`, { type: 'application/zip' });
    const { file_url: zipUrl } = await base44.asServiceRole.integrations.Core.UploadPublicFile({ file });

    const claimUrl = `https://hypersonic-sync-your-gear.base44.app/claim?serial=${encodeURIComponent(serial)}`;
    const html = `
      <div style="font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', sans-serif; max-width: 520px; margin: 0 auto; color: #1f2937;">
        <h2 style="margin: 0 0 8px;">QR code for serial ${serial}</h2>
        <p style="margin: 0 0 16px; color: #6b7280;">Scanning this code opens the app and adds the product to the user's catalog after confirmation.</p>
        <p style="margin: 0 0 8px;"><strong>Claim link:</strong><br><a href="${claimUrl}">${claimUrl}</a></p>
        <p style="margin: 16px 0 8px;"><strong>QR files (PNG + SVG):</strong><br><a href="${zipUrl}">Download ${base}.zip</a></p>
        <hr style="margin: 24px 0; border: none; border-top: 1px solid #e5e7eb;">
        <p style="margin: 0; font-size: 12px; color: #9ca3af;">Generated by ProductSync Pro · QR Code Generator</p>
      </div>`;

    await base44.asServiceRole.integrations.Core.SendEmail({
      to: user.email,
      subject: `QR code for serial ${serial}`,
      html
    });

    return Response.json({ status: 'sent', to: user.email, zip_url: zipUrl });
  } catch (error) {
    return Response.json({ error: error.message }, { status: 500 });
  }
}